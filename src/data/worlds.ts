/**
 * Ziggy World — the 20 worlds of the map, in path order.
 * Each world tells a small story in 3 chapters of 2 quests; every quest is a
 * game of the Arcade that trains one skill and moves the story forward.
 */
import type { L } from '@/lib/i18n-text';
import type { LearningSkill } from '@/lib/learning/skills';
import type { ArcadeGameId } from '@/lib/arcade/types';
import type { QuestDefinition, WorldDefinition } from './types';

type QuestSpec = {
  game: ArcadeGameId;
  skill: LearningSkill;
  title: L;
  intro: L;
  outcome: QuestDefinition['outcome'];
};

type WorldSpec = Omit<WorldDefinition, 'quests'> & { quests: QuestSpec[] };

/** XP grows gently along a world's story. */
const QUEST_XP = [10, 12, 15, 18, 22, 25];

function world(spec: WorldSpec): WorldDefinition {
  return {
    ...spec,
    quests: spec.quests.map((q, i) => ({
      id: `${spec.id}_q${i + 1}`,
      title: q.title,
      intro: q.intro,
      gameId: q.game,
      skill: q.skill,
      chapter: (Math.floor(i / 2) + 1) as 1 | 2 | 3,
      outcome: q.outcome,
      reward: { xp: QUEST_XP[i], stars: 1 },
    })),
  };
}

