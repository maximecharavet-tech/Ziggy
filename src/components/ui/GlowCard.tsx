'use client';

import { ReactNode } from 'react';
import { JuicySurface } from './fx/JuicySurface';

interface GlowCardProps {
  children: ReactNode;
  className?: string;
  /** A theme colour name (green, sky, coral, purple…): `--color-<name>` in globals.css. */
  glowColor?: string;
  active?: boolean;
}

/**
 * A glass card with a soft coloured rim on hover. It lifts and catches a
 * sheen of light under the mouse, and squishes under a finger.
 */
export function GlowCard({ children, className = '', glowColor = 'green', active = false }: GlowCardProps) {
  // Inline colour (a class built from a variable would never be generated by Tailwind).
  const tint = `var(--color-${glowColor}, var(--color-green))`;
  return (
    <JuicySurface className={`group rounded-2xl ${className}`} lift={5}>
      <div
        className={`pointer-events-none absolute -inset-[1px] rounded-2xl opacity-0 blur-sm transition-opacity duration-500 ${
          active ? 'opacity-100' : 'group-hover:opacity-100'
        }`}
        style={{ background: `linear-gradient(90deg, transparent, color-mix(in srgb, ${tint} 30%, transparent), transparent)` }}
        aria-hidden="true"
      />
      <div className="relative h-full bg-bg-card/80 backdrop-blur-xl rounded-2xl border border-border/50 p-6 transition-[border-color,box-shadow] duration-300 hover:border-green/30 hover:shadow-[0_8px_30px_rgba(34,197,94,0.08)]">
        {children}
      </div>
    </JuicySurface>
  );
}
