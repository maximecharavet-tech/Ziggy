#!/usr/bin/env node
/**
 * Builds docs/TECHNOLOGY_REGISTRY.md from every research cell's registry
 * (research/<cell>/registry.md, format in research/technology-registry/FORMAT.md):
 * one table sorted by decision then score, plus per-decision counts.
 *   node scripts/tech-registry.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cells = readdirSync(join(root, 'research')).filter((d) => existsSync(join(root, 'research', d, 'registry.md')));
const rows = [];
let header = null;
for (const cell of cells) {
  const lines = readFileSync(join(root, 'research', cell, 'registry.md'), 'utf8').split('\n').filter((l) => l.trim().startsWith('|'));
  for (const l of lines) {
    const cols = l.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
    if (/^-+$/.test(cols[0].replace(/:/g, '')) || cols.every((c) => /^:?-*:?$/.test(c))) continue;
    if (/^name$/i.test(cols[0])) {
      header ??= cols;
      continue;
    }
    if (cols.length < 16) continue;
    rows.push({ cell, cols });
  }
}
const order = { adopt: 0, test: 1, reject: 2 };
const score = (r) => Number(String(r.cols[13]).replace(/[^\d.]/g, '')) || 0;
const decision = (r) => String(r.cols[14]).toLowerCase().replace(/[^a-z]/g, '');
rows.sort((a, b) => (order[decision(a)] ?? 3) - (order[decision(b)] ?? 3) || score(b) - score(a) || a.cols[0].localeCompare(b.cols[0]));
const count = (d) => rows.filter((r) => decision(r) === d).length;
const cols = ['Cell', ...(header ?? [])];
const out = [
  '# Technology registry',
  '',
  `Generated by \`node scripts/tech-registry.mjs\` from ${cells.map((c) => `\`research/${c}/registry.md\``).join(', ')} — do not edit by hand: edit the cell registries and re-run.`,
  '',
  'Scoring (/100): quality 20 · Ziggy fit 20 · performance 15 · maturity 10 · documentation 10 · licence & commercial use 15 · running cost 10. Rules in `research/technology-registry/FORMAT.md`. Code licence and weights licence are separate; unknown or non-commercial weights score 0 on licence and are never adopted.',
  '',
  `**${rows.length} technologies** — adopt ${count('adopt')}, test ${count('test')}, reject ${count('reject')}.`,
  '',
  `| ${cols.join(' | ')} |`,
  `| ${cols.map(() => '---').join(' | ')} |`,
  ...rows.map((r) => `| ${[r.cell, ...r.cols].join(' | ')} |`),
  '',
];
writeFileSync(join(root, 'docs/TECHNOLOGY_REGISTRY.md'), out.join('\n'));
console.log(`docs/TECHNOLOGY_REGISTRY.md: ${rows.length} rows (adopt ${count('adopt')}, test ${count('test')}, reject ${count('reject')})`);
