#!/usr/bin/env node
/**
 * Builds the Bac à sable magique engine (Rust, rust/sandbox-core) to
 * WebAssembly into src/games2d/sandbox/wasm/. The built files are committed:
 * Vercel has no Rust toolchain. Run it after any change to rust/sandbox-core/.
 *
 * It first turns the data file rust/sandbox-core/data/sandbox.json (elements
 * and reactions) into code: rust/sandbox-core/src/gen.rs (const tables for the
 * engine) and src/games2d/sandbox/wasm/ids.ts (the same ids for the page).
 *
 *   npm run sandbox:wasm                      # generate, test, build, write src/games2d/sandbox/wasm/
 *   npm run sandbox:wasm -- --skip-tests      # generate and build only
 *   npm run sandbox:wasm -- --gen             # generate the tables only
 *   npm run sandbox:wasm -- --check           # regenerate + rebuild in a temp dir; fail if committed files differ (CI)
 *
 * Needs: rustup target add wasm32-unknown-unknown
 *        cargo install wasm-bindgen-cli --version <the crate's pinned wasm-bindgen version>
 * wasm-opt (binaryen) is used when it is on the PATH, never installed. The
 * build is reproducible for a given rustc + wasm-bindgen (+ wasm-opt): paths
 * are remapped so the output does not depend on the machine.
 */
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, mkdtempSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir, homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const crate = join(root, 'rust/sandbox-core');
const out = join(root, 'src/games2d/sandbox/wasm');
const args = new Set(process.argv.slice(2));
const check = args.has('--check');
const genOnly = args.has('--gen');
const skipTests = args.has('--skip-tests') || check;
const NAME = 'sandbox_core';
const FILES = [`${NAME}.js`, `${NAME}.d.ts`, `${NAME}_bg.wasm`, `${NAME}_bg.wasm.d.ts`];

function fail(msg) {
  console.error(`\n✗ sandbox:wasm: ${msg}\n`);
  process.exit(1);
}

function run(cmd, argv, opts = {}) {
  const r = spawnSync(cmd, argv, { stdio: 'inherit', ...opts });
  if (r.error) fail(`${cmd} not found (${r.error.message})`);
  if (r.status !== 0) fail(`${cmd} ${argv.join(' ')} exited with ${r.status}`);
}

function tool(cmd, argv) {
  try {
    return execFileSync(cmd, argv, { encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

/* ── Code generation from the data file ─────────────────────────────── */

const KINDS = ['solid', 'powder', 'liquid', 'gas', 'special'];
const FLAGS = ['loose', 'opaque', 'flutter', 'hover'];
const STYLES = ['none', 'grain', 'liquid', 'rock', 'gas', 'cloud', 'bubble', 'plant', 'flower', 'ice', 'lamp', 'glass', 'crystal', 'lava', 'soft', 'coral', 'pipe', 'star', 'snow', 'wet', 'pebble', 'orb'];

function generate() {
  const data = JSON.parse(readFileSync(join(crate, 'data/sandbox.json'), 'utf8'));
  const els = data.elements;
  const byKey = new Map(els.map((e) => [e.key, e]));
  const reactions = data.reactions.map((r) => r.id);
  if (els.length > 64) fail('at most 64 elements (6 bits per cell)');
  if (reactions.length > 127) fail('at most 127 reactions (7 bits per event)');
  els.forEach((e, k) => e.id === k || fail(`element ${e.key}: id ${e.id} must equal its position ${k}`));
  if (new Set(els.map((e) => e.key)).size !== els.length) fail('duplicate element key');
  if (new Set(reactions).size !== reactions.length) fail('duplicate reaction id');
  const el = (key, what) => {
    if (key === undefined || key === null) return 255;
    const e = byKey.get(key);
    if (!e) fail(`${what}: unknown element "${key}"`);
    return e.id;
  };
  const ev = (id, what) => {
    if (id === undefined || id === null) return 255;
    const k = reactions.indexOf(id);
    if (k < 0) fail(`${what}: unknown reaction "${id}"`);
    return k;
  };
  const hex = (s, what) => {
    if (!s) return '0';
    if (!/^#[0-9a-f]{6}$/i.test(s)) fail(`${what}: bad colour ${s}`);
    return `0x${s.slice(1).toLowerCase()}`;
  };
  const C = (s) => s.toUpperCase();

  let rs = '// Generated by scripts/sandbox-wasm.mjs from data/sandbox.json. Do not edit by hand.\n';
  rs += 'use crate::table::{Element, Rule};\n\n';
  rs += `pub const ELEMENT_COUNT: usize = ${els.length};\n`;
  for (const e of els) rs += `pub const ${C(e.key)}: u8 = ${e.id};\n`;
  rs += `\npub const REACTION_COUNT: usize = ${reactions.length};\n`;
  reactions.forEach((r, k) => (rs += `pub const R_${C(r)}: u8 = ${k};\n`));
  rs += '\n';
  KINDS.forEach((k, n) => (rs += `pub const K_${C(k)}: u8 = ${n};\n`));
  FLAGS.forEach((k, n) => (rs += `pub const F_${C(k)}: u8 = ${1 << n};\n`));
  STYLES.forEach((k, n) => (rs += `pub const S_${C(k)}: u8 = ${n};\n`));
  rs += `\npub static ELEMENTS: [Element; ELEMENT_COUNT] = [\n`;
  for (const e of els) {
    const kind = KINDS.indexOf(e.kind);
    const style = STYLES.indexOf(e.style);
    if (kind < 0) fail(`${e.key}: unknown kind ${e.kind}`);
    if (style < 0) fail(`${e.key}: unknown style ${e.style}`);
    let flags = 0;
    for (const f of e.flags ?? []) {
      const k = FLAGS.indexOf(f);
      if (k < 0) fail(`${e.key}: unknown flag ${f}`);
      flags |= 1 << k;
    }
    const hot = e.hot ?? [0, null, null];
    const cold = e.cold ?? [0, null, null];
    rs +=
      `    Element { kind: ${kind}, density: ${e.density ?? 255}, rate: ${e.rate ?? 255}, slide: ${e.slide ?? 0}, spread: ${e.spread ?? 0}, ` +
      `paint: ${e.paint ?? 100}, life: ${e.life ?? 0}, flags: ${flags}, style: ${style}, rgb: ${hex(e.rgb, e.key)}, rgb2: ${hex(e.rgb2 ?? e.rgb, e.key)}, ` +
      `glow: ${hex(e.glow, e.key)}, alpha: ${e.alpha ?? 255}, hot_at: ${hot[0]}, hot_to: ${el(hot[1], e.key)}, hot_ev: ${ev(hot[2], e.key)}, ` +
      `cold_at: ${cold[0]}, cold_to: ${el(cold[1], e.key)}, cold_ev: ${ev(cold[2], e.key)}, heat: ${e.heat ?? 0} }, // ${e.key}\n`;
  }
  rs += '];\n\n';
  const rules = [];
  for (const r of data.reactions)
    for (const rule of r.rules ?? []) rules.push({ ...rule, event: rule.quiet ? null : r.id, what: r.id });
  for (const rule of data.quietRules ?? []) rules.push({ ...rule, what: 'quietRules' });
  rs += `pub static RULES: [Rule; ${rules.length}] = [\n`;
  for (const r of rules) {
    if (!(r.chance >= 1 && r.chance <= 1000)) fail(`${r.what}: chance must be 1..1000`);
    rs += `    Rule { a: ${el(r.a, r.what)}, b: ${el(r.b, r.what)}, chance: ${r.chance}, out_a: ${el(r.outA, r.what)}, out_b: ${el(r.outB, r.what)}, event: ${ev(r.event, r.what)}, hue: ${r.hue ? 'true' : 'false'} }, // ${r.a} + ${r.b}\n`;
  }
  rs += '];\n';

  let ts = '// Generated by scripts/sandbox-wasm.mjs from rust/sandbox-core/data/sandbox.json. Do not edit by hand.\n';
  ts += '/** Element ids, as stored in the cells and in saved worlds (never renumbered). */\n';
  ts += `export const EL = {\n${els.map((e) => `  ${e.key}: ${e.id},`).join('\n')}\n} as const;\n`;
  ts += 'export type ElementKey = keyof typeof EL;\n';
  ts += `export const ELEMENT_COUNT = ${els.length};\n\n`;
  ts += '/** Reaction ids, in the order of the engine event numbers (kept in the notebook save: never renamed). */\n';
  ts += `export const REACTIONS = [\n${reactions.map((r) => `  '${r}',`).join('\n')}\n] as const;\n`;
  ts += 'export type Reaction = (typeof REACTIONS)[number];\n';
  return { 'gen.rs': rs, 'ids.ts': ts };
}

const generated = generate();
const genTargets = { 'gen.rs': join(crate, 'src/gen.rs'), 'ids.ts': join(out, 'ids.ts') };
if (check) {
  for (const [name, path] of Object.entries(genTargets)) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== generated[name]) fail(`${path} is out of date with data/sandbox.json: run \`npm run sandbox:wasm\``);
  }
} else {
  mkdirSync(out, { recursive: true });
  for (const [name, path] of Object.entries(genTargets)) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== generated[name]) writeFileSync(path, generated[name]);
  }
}
if (genOnly) {
  console.log('✓ sandbox:wasm: tables generated');
  process.exit(0);
}

/* ── Build ──────────────────────────────────────────────────────────── */

// wasm-bindgen CLI must match the crate's pinned wasm-bindgen exactly.
const pinned = /wasm-bindgen\s*=\s*"=([0-9.]+)"/.exec(readFileSync(join(crate, 'Cargo.toml'), 'utf8'))?.[1];
const cli = tool('wasm-bindgen', ['--version'])?.split(/\s+/)[1];
if (!pinned) fail('rust/sandbox-core/Cargo.toml must pin wasm-bindgen with "=x.y.z"');
if (!cli) fail(`wasm-bindgen CLI not found: cargo install wasm-bindgen-cli --version ${pinned}`);
if (cli !== pinned) fail(`wasm-bindgen CLI ${cli} ≠ crate ${pinned}: cargo install wasm-bindgen-cli --version ${pinned}`);

if (!skipTests) run('cargo', ['test', '--quiet', '--manifest-path', join(crate, 'Cargo.toml')]);

const cargoHome = process.env.CARGO_HOME || join(homedir(), '.cargo');
const rustflags = [`--remap-path-prefix=${cargoHome}=/cargo`, `--remap-path-prefix=${crate}=/sandbox-core`, process.env.RUSTFLAGS || ''].join(' ').trim();
const dest = check ? mkdtempSync(join(tmpdir(), 'sandbox-wasm-')) : out;
mkdirSync(dest, { recursive: true });
const wasmOpt = tool('wasm-opt', ['--version']);
run('cargo', ['build', '--release', '--quiet', '--target', 'wasm32-unknown-unknown', '--manifest-path', join(crate, 'Cargo.toml')], { env: { ...process.env, RUSTFLAGS: rustflags } });
run('wasm-bindgen', ['--target', 'web', '--out-dir', dest, '--out-name', NAME, join(crate, 'target/wasm32-unknown-unknown/release/sandbox_core.wasm')]);
if (wasmOpt) {
  const wasm = join(dest, `${NAME}_bg.wasm`);
  run('wasm-opt', ['-O3', '--enable-bulk-memory', '--enable-nontrapping-float-to-int', '--enable-sign-ext', '--enable-mutable-globals', wasm, '-o', wasm]);
}
console.log(wasmOpt ? `wasm-opt: ${wasmOpt}` : 'wasm-opt: not found, skipped');

if (check) {
  const bad = [];
  for (const f of FILES) {
    const a = join(dest, f);
    const b = join(out, f);
    if (!existsSync(b)) bad.push(`${f}: missing in src/games2d/sandbox/wasm/`);
    else if (!readFileSync(a).equals(readFileSync(b))) bad.push(`${f}: differs`);
  }
  const extra = readdirSync(dest).filter((f) => !FILES.includes(f));
  rmSync(dest, { recursive: true, force: true });
  if (extra.length) bad.push(`unexpected outputs: ${extra.join(', ')}`);
  if (bad.length) {
    fail(
      `the committed WebAssembly is out of date:\n  ${bad.join('\n  ')}\n` +
        `Run \`npm run sandbox:wasm\` and commit src/games2d/sandbox/wasm/ ` +
        `(same toolchain: ${tool('rustc', ['--version'])}, wasm-bindgen ${cli}${wasmOpt ? `, ${wasmOpt}` : ''}).`,
    );
  }
  console.log('✓ sandbox:wasm --check: src/games2d/sandbox/wasm/ is up to date');
} else {
  for (const f of FILES) {
    const p = join(out, f);
    const size = statSync(p).size;
    const gz = gzipSync(readFileSync(p), { level: 9 }).length;
    console.log(`${f.padEnd(26)} ${(size / 1024).toFixed(1).padStart(7)} kB  (gzip ${(gz / 1024).toFixed(1)} kB)`);
  }
}
