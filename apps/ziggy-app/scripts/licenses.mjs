#!/usr/bin/env node
// Lists the Rust crates compiled into the Android and iOS apps with their licence, writes
// THIRD_PARTY_CRATES.md, and fails if one is outside the project's licence rule
// (MIT / Apache-2.0 / BSD, see CLAUDE.md). Unicode-3.0 is reported for the owner's OK.
//   node apps/ziggy-app/scripts/licenses.mjs
// Needs: cargo, and `rustup target add aarch64-linux-android aarch64-apple-ios`.

import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const crate = join(app, 'src-tauri');
const run = (cmd) => execSync(cmd, { cwd: crate, maxBuffer: 256 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'] }).toString();

const shipped = new Map();
for (const [target, label] of [
  ['aarch64-linux-android', 'Android'],
  ['aarch64-apple-ios', 'iOS'],
]) {
  for (const line of run(`cargo tree --target ${target} -e normal,no-proc-macro --prefix none`).split('\n')) {
    const m = /^(\S+) v(\S+)/.exec(line.trim());
    if (!m || m[1] === 'ziggy-app') continue;
    const key = `${m[1]} ${m[2]}`;
    shipped.set(key, (shipped.get(key) ?? new Set()).add(label));
  }
}

const meta = JSON.parse(run('cargo metadata --format-version 1'));
const pkgs = new Map(meta.packages.map((p) => [`${p.name} ${p.version}`, p]));
const ok = (licence) =>
  licence
    .replace(/[()]/g, '')
    .split(/ OR |\//)
    .some((alt) => alt.split(' AND ').every((l) => /^(MIT|Apache-2\.0|BSD-[23]-Clause)$/.test(l.trim())));

const rows = [];
const review = [];
for (const [key, targets] of [...shipped].sort()) {
  const p = pkgs.get(key) ?? {};
  const [name, version] = key.split(' ');
  let licence = p.license ?? '?';
  if (!p.source && ['option-ext', 'dom_query'].includes(name)) licence = 'MIT (Ziggy drop-in, src-tauri/patches/)';
  rows.push(`| ${name} | ${version} | ${licence} | ${[...targets].sort().join(', ')} | ${p.repository ?? `https://crates.io/crates/${name}`} |`);
  if (!licence.startsWith('MIT (Ziggy') && !ok(licence)) review.push(`${key}: ${licence}`);
}

writeFileSync(
  join(app, 'THIRD_PARTY_CRATES.md'),
  [
    '# Crates compiled into the Ziggy AI apps',
    '',
    'Generated by `scripts/licenses.mjs` from `cargo tree -e normal,no-proc-macro` for `aarch64-linux-android`',
    'and `aarch64-apple-ios` (build-time tools and procedural macros run only on the build machine and are not',
    'listed). Where a crate offers a choice ("MIT OR Apache-2.0"), Ziggy uses it under MIT or Apache-2.0.',
    '',
    '| Crate | Version | Licence | In | Source |',
    '|---|---|---|---|---|',
    ...rows,
    '',
  ].join('\n'),
);

console.log(`${rows.length} crates written to THIRD_PARTY_CRATES.md`);
const notAllowed = review.filter((r) => !/Unicode-3\.0/.test(r));
if (review.length) console.log(`Outside MIT/Apache/BSD (owner's OK needed):\n  ${review.join('\n  ')}`);
if (notAllowed.some((r) => /MPL|GPL|LGPL|AGPL|NC/.test(r))) {
  console.error('Copyleft licence in the shipped code: not allowed.');
  process.exit(1);
}
